"""Storage interfaces: one Protocol per collection, combined into a single Registry."""
from __future__ import annotations

from typing import Protocol

from ..core.schemas import AgentRecord, ModelConfig, OrchestratorRecord, RunTrace, ToolRecord


class AgentStore(Protocol):
    def save(self, record: AgentRecord) -> AgentRecord: ...
    def get(self, name: str, version: int | None = None) -> AgentRecord | None: ...
    def list(self) -> list[AgentRecord]: ...
    def next_version(self, name: str) -> int: ...


class ModelStore(Protocol):
    def save_model(self, model: ModelConfig) -> ModelConfig: ...
    def get_model(self, model_id: str) -> ModelConfig | None: ...
    def list_models(self) -> list[ModelConfig]: ...


class RunStore(Protocol):
    def save_run(self, run: RunTrace) -> RunTrace: ...
    def get_run(self, run_id: str) -> RunTrace | None: ...
    def list_runs(self, target: str | None = None, limit: int = 20) -> list[RunTrace]: ...


class OrchestratorStore(Protocol):
    def save_orchestrator(self, record: OrchestratorRecord) -> OrchestratorRecord: ...
    def get_orchestrator(
        self, name: str, version: int | None = None, status: str | None = "approved"
    ) -> OrchestratorRecord | None: ...
    def list_orchestrators(self) -> list[OrchestratorRecord]: ...


class ToolStore(Protocol):
    def save_tool(self, record: ToolRecord) -> ToolRecord: ...
    def get_tool(self, name: str, version: int | None = None) -> ToolRecord | None: ...
    def list_tools(self) -> list[ToolRecord]: ...
    def set_tool_status(self, name: str, version: int, status: str) -> None: ...


class Registry(AgentStore, ModelStore, RunStore, OrchestratorStore, ToolStore, Protocol):
    """Everything the builders and runtime need from storage."""
